import { readdirSync, statSync, writeFileSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const BUILD_DIR = new URL("../build", import.meta.url).pathname;

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}

const assets = walk(BUILD_DIR)
  .map((file) => `./${relative(BUILD_DIR, file).split("\\").join("/")}`)
  .filter((file) => !file.endsWith("sw.js"));

const hash = createHash("sha256");
for (const asset of assets.sort()) {
  hash.update(asset);
  hash.update(readFileSync(join(BUILD_DIR, asset)));
}
const version = hash.digest("hex").slice(0, 12);

const sw = `/* Generated by scripts/build-sw.js — do not edit. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = \`aurora-shell-\${VERSION}\`;
const DATA_CACHE = "aurora-data";
const SHELL = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key !== SHELL_CACHE && key !== DATA_CACHE)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);

  if (/open-meteo\\.com|bigdatacloud\\.net/.test(url.hostname)) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(DATA_CACHE).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request, { ignoreVary: true }))
    );
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches
          .match("./index.html", { ignoreVary: true })
          .then((cached) => cached ?? caches.match("./", { ignoreVary: true }))
      )
    );
    return;
  }

  // ignoreVary: precached entries were fetched by addAll, whose request
  // headers differ from the page's. A default match compares them and misses.
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches
        .match(request, { ignoreVary: true })
        .then((cached) => cached ?? fetch(request))
    );
  }
});
`;

writeFileSync(join(BUILD_DIR, "sw.js"), sw);
console.log(
  `sw.js written — ${assets.length} shell assets, version ${version}`
);
